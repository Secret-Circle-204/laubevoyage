const dictDir = path.resolve(process.cwd(), 'src/dictionaries')

for (const loc of LOCALES) {
  const filePath = path.join(dictDir, `${loc}.json`)
  const content = JSON.parse(fs.readFileSync(filePath, 'utf-8'))
  content.search = SEARCH_TRANSLATIONS[loc]
  fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf-8')
  console.log(`Updated ${loc}.json with ${Object.keys(content.search).length} search keys.`)
}

console.log('All 13 dictionaries successfully updated!')
